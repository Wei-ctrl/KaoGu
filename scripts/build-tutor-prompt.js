#!/usr/bin/env node
// Builds tutor/chemistry-prompt.js (the Chemistry Tutor's system prompt) from
// prompts/tutor.md plus §2, §4 and §5 of prompts/chemistry.md, so the tutor
// teaches the same topics, answer-key conventions and reference data as the
// daily sets. Run it again after editing either prompt:
//   node scripts/build-tutor-prompt.js

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");

const tutor = read("prompts/tutor.md").split(/^# SYSTEM PROMPT\s*$/m)[1];
if (!tutor) throw new Error("prompts/tutor.md needs a '# SYSTEM PROMPT' heading");

const chem = read("prompts/chemistry.md");
function section(n) {
  const m = chem.match(new RegExp("^## " + n + "\\..*$[\\s\\S]*?(?=^## \\d+\\.|(?![\\s\\S]))", "m"));
  if (!m) throw new Error("prompts/chemistry.md has no §" + n);
  return m[0].trim();
}

const prompt = [
  tutor.trim(),
  "# Course reference (僑先部 化學 Ch1–Ch2)",
  section(2),
  section(4),
  section(5)
].join("\n\n") + "\n";

const out = "// Generated by scripts/build-tutor-prompt.js from prompts/tutor.md and prompts/chemistry.md. Do not edit.\n" +
  "window.KAOGU_TUTOR_PROMPT = " + JSON.stringify(prompt) + ";\n";

fs.mkdirSync(path.join(root, "tutor"), { recursive: true });
fs.writeFileSync(path.join(root, "tutor/chemistry-prompt.js"), out);
console.log("Wrote tutor/chemistry-prompt.js (" + prompt.length + " chars)");
